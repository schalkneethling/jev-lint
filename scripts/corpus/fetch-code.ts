// Builds a corpus of real open-source JavaScript and TypeScript, chosen by a seeded random sample of
// GitHub's search index so that neither the rule author nor the prompts influence what gets tested. It is
// what `fetch.ts` is for the HTML rules: the five code rules have so far met only fixtures written by their
// own author, which is exactly where the HTML rules stood before their first corpus (findings §21).
//
//   node scripts/corpus/fetch-code.ts [--seed 1] [--repos 60] [--out corpus-code]
//
// Per repository: a shallow clone of the default branch, then a seeded sample of source files, and the rest
// of the clone deleted so the snapshot stays small. Test files are taken deliberately, because one rule only
// applies to them, and `.jsx`/`.tsx` files are taken deliberately too, because the nine HTML rules read the
// markup in them through `parseJsx`.
//
// The repo keeps the manifest. Snapshots quote other people's code: they stay in gitignored paths and are
// rebuilt from the seed and the commit SHAs the manifest records.
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, extname } from "node:path";
import { parseArgs, promisify } from "node:util";

const run = promisify(execFile);

const { values } = parseArgs({
  options: { seed: { type: "string", default: "1" }, repos: { type: "string", default: "60" }, out: { type: "string", default: "corpus-code" } },
});

// Star bands, sampled equally: a package with 30 stars is written and reviewed very differently from one
// with 50,000, and a corpus taken from the top of a ranking would only ever show the second kind.
const BANDS = [
  { name: "10-100", stars: "10..100" },
  { name: "100-1k", stars: "100..1000" },
  { name: "1k-10k", stars: "1000..10000" },
  { name: "10k+", stars: ">=10000" },
] as const;

const LANGUAGES = ["javascript", "typescript"] as const;

// Permissive only: the corpus is read, quoted in a label bench, and discussed in findings.
const LICENCES = ["mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc"];

// GitHub search returns at most 1,000 results per query and orders them, so the top of one broad query is the
// same few famous repositories every time. Each slice is narrowed by when the repository was created, and
// which windows a slice uses is drawn from the seed: variety comes from the query, never from a rank.
const WINDOWS = [
  ["2010-01-01", "2013-01-01"],
  ["2013-01-01", "2015-01-01"],
  ["2015-01-01", "2017-01-01"],
  ["2017-01-01", "2019-01-01"],
  ["2019-01-01", "2021-01-01"],
  ["2021-01-01", "2023-01-01"],
  ["2023-01-01", "2026-01-01"],
] as const;
const WINDOWS_PER_SLICE = 3;
const PER_QUERY = 40;

// Two years of no pushes is an abandoned repository, whose code is not what people write today.
const PUSHED_SINCE = new Date(Date.now() - 2 * 365 * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);

// Kilobytes. A monorepo of a gigabyte costs minutes to clone for the same ten files a small one gives in
// seconds; the search result carries the size, so the clone never starts.
const MAX_REPO_SIZE = 150_000;

// Every network and process step gets its own deadline. The HTML fetcher once parked every worker for good
// on an in-page `fetch` with no timeout (findings §19), and a `git clone` that stalls behaves the same way.
const SEARCH_TIMEOUT = 60_000;
const CLONE_TIMEOUT = 180_000;
const GIT_TIMEOUT = 30_000;
const CLONES_AT_ONCE = 4;

const SOURCE_EXTENSIONS = [".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx"];
// Directories nobody writes by hand. `vendor` and `build` are conventions, not guarantees, so the
// generated-file tests below still run on everything that survives this.
const EXCLUDED_DIRECTORIES = ["node_modules", "dist", "build", "vendor", ".git"];
// A bundle has no line breaks to speak of, and a code generator says so in a header. Both produce files
// full of candidates that no person wrote and no person will fix.
const MAX_LINE_LENGTH = 500;
const GENERATED_HEADER = /@generated|auto-?generated|automatically generated|do not edit|this file (?:is|was) generated|code generated by/i;
const HEADER_CHARS = 2_000;
// Under 30 lines is a barrel file or a one-line export; over 1,500 is usually a bundle, a fixture dump, or
// a file whose sampled candidates would all come from one place.
const MIN_LINES = 30;
const MAX_LINES = 1_500;

// Files per repository, drawn from the seed. About ten each over sixty repositories is the 500 to 600 files
// the run is for.
const FILES_PER_REPO = [8, 11] as const;
// A repository with almost nothing eligible contributes a biased handful, so it is skipped instead.
const MIN_FILES_PER_REPO = 4;
// One rule applies only to tests and the HTML rules only read files that hold JSX, so neither kind can be
// left to chance. The shares are ceilings per repository, set above the corpus-wide targets of a quarter and
// a fifth because plenty of repositories have no tests to take and most have no JSX at all.
const TEST_SHARE = 0.3;
const JSX_SHARE = 0.35;

type Kind = "source" | "test" | "jsx";

interface Repo {
  fullName: string;
  stargazersCount: number;
  defaultBranch: string;
  size: number;
  license: { key: string } | null;
}

interface ManifestEntry {
  repo: string;
  band: string;
  stars: number;
  license: string;
  sha: string;
  path: string;
  file: string;
  kind: Kind;
  sha256: string;
}

interface Slice {
  language: string;
  band: string;
  created: string;
  found: number;
}

/** mulberry32: a small seeded generator, so the same seed always asks for the same corpus. */
function random(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffled<T>(items: T[], next: () => number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [out[i], out[j]] = [out[j]!, out[i]!];
  }
  return out;
}

const skipped: Record<string, number> = {};
const skip = (reason: string) => void (skipped[reason] = (skipped[reason] ?? 0) + 1);

/** One search slice: a language, a star band, and a window of creation dates. */
async function search(language: string, band: (typeof BANDS)[number], created: string): Promise<Repo[]> {
  const { stdout } = await run(
    "gh",
    [
      "search",
      "repos",
      `pushed:>${PUSHED_SINCE}`,
      `created:${created}`,
      `--language=${language}`,
      `--license=${LICENCES.join(",")}`,
      "--archived=false",
      "--include-forks=false",
      `--stars=${band.stars}`,
      `--limit=${PER_QUERY}`,
      "--json=fullName,stargazersCount,defaultBranch,size,license",
    ],
    { timeout: SEARCH_TIMEOUT, maxBuffer: 16 * 1024 * 1024 },
  );
  return JSON.parse(stdout) as Repo[];
}

const testFile = (path: string) => /(?:^|\/)(?:__tests__|__test__|tests?|specs?|e2e)\//i.test(path) || /\.(?:test|spec)\.[mc]?[jt]sx?$/i.test(path);

function kindOf(path: string): Kind {
  // Test first: `test-title-matches-body` is the only rule that can classify a `.test.tsx` at all, and the
  // HTML rules read the JSX in it either way, because `run()` parses every code file twice.
  if (testFile(path)) return "test";
  return [".jsx", ".tsx"].includes(extname(path)) ? "jsx" : "source";
}

/** Whether a tracked file is source a person wrote, rather than a bundle, a generated file, or a stub. */
function eligible(path: string, source: string): boolean {
  const lines = source.split("\n");
  if (lines.length < MIN_LINES || lines.length > MAX_LINES) return false;
  if (lines.some((line) => line.length > MAX_LINE_LENGTH)) return false;
  return !GENERATED_HEADER.test(source.slice(0, HEADER_CHARS));
}

/**
 * Takes the seeded sample from one clone: a ceiling on tests and on JSX first, then whatever source files
 * are left, so a repository of nothing but components cannot use up the whole quota with one kind.
 */
function sampleFiles(candidates: { path: string; kind: Kind }[], target: number, next: () => number): { path: string; kind: Kind }[] {
  const pool = shuffled(candidates, next);
  const ceilings: Record<Kind, number> = { test: Math.ceil(target * TEST_SHARE), jsx: Math.ceil(target * JSX_SHARE), source: target };
  const taken: { path: string; kind: Kind }[] = [];
  // One kind at a time, the two scarce ones first. Taking the shuffled pool in one pass instead gave a
  // corpus of 19% tests and 10% JSX against targets of 25% and 20%: plain source is the bulk of any
  // repository, so it reached the quota before the kinds only some rules can read were seen at all.
  for (const kind of ["test", "jsx", "source"] as Kind[]) {
    const ofKind = pool.filter((file) => file.kind === kind).slice(0, ceilings[kind]);
    taken.push(...ofKind.slice(0, target - taken.length));
  }
  return taken;
}

const snapshots = `${values.out}/snapshots`;
mkdirSync(snapshots, { recursive: true });

async function take(repo: Repo, band: string, next: () => number): Promise<ManifestEntry[]> {
  const dir = `${snapshots}/${repo.fullName.replace("/", "__")}`;
  rmSync(dir, { recursive: true, force: true });
  // A repository that has been made private or deleted between the search and the clone would otherwise
  // block on a credential prompt until the timeout; this turns it into a failure straight away.
  const git = { timeout: CLONE_TIMEOUT, env: { ...process.env, GIT_TERMINAL_PROMPT: "0" }, maxBuffer: 64 * 1024 * 1024 };
  try {
    await run("git", ["clone", "--depth=1", "--single-branch", `--branch=${repo.defaultBranch}`, `https://github.com/${repo.fullName}.git`, dir], git);
  } catch {
    rmSync(dir, { recursive: true, force: true });
    return (skip("clone failed"), []);
  }

  const [{ stdout: sha }, { stdout: tracked }] = await Promise.all([
    run("git", ["-C", dir, "rev-parse", "HEAD"], { ...git, timeout: GIT_TIMEOUT }),
    run("git", ["-C", dir, "ls-files", "-z"], { ...git, timeout: GIT_TIMEOUT }),
  ]);

  const candidates: { path: string; kind: Kind }[] = [];
  const sources = new Map<string, string>();
  for (const path of tracked.split("\0").filter(Boolean)) {
    if (!SOURCE_EXTENSIONS.includes(extname(path))) continue;
    if (path.endsWith(".d.ts") || path.includes(".min.")) continue;
    if (path.split("/").some((segment) => EXCLUDED_DIRECTORIES.includes(segment))) continue;
    let source: string;
    try {
      source = readFileSync(`${dir}/${path}`, "utf8");
    } catch {
      // A symlink pointing outside the clone, or a path the filesystem cannot spell.
      continue;
    }
    if (!eligible(path, source)) continue;
    candidates.push({ path, kind: kindOf(path) });
    sources.set(path, source);
  }
  if (candidates.length < MIN_FILES_PER_REPO) {
    rmSync(dir, { recursive: true, force: true });
    return (skip("too few source files"), []);
  }

  const target = FILES_PER_REPO[0] + Math.floor(next() * (FILES_PER_REPO[1] - FILES_PER_REPO[0] + 1));
  const kept = sampleFiles(candidates, target, next);
  // Everything else goes, history included: the snapshot is the sampled files and nothing more.
  rmSync(dir, { recursive: true, force: true });
  return kept.map(({ path, kind }) => {
    const source = sources.get(path)!;
    const file = `${dir}/${path}`;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
    return {
      repo: repo.fullName,
      band,
      stars: repo.stargazersCount,
      license: repo.license?.key ?? "unknown",
      sha: sha.trim(),
      path,
      file,
      kind,
      sha256: createHash("sha256").update(source).digest("hex"),
    };
  });
}

const next = random(Number(values.seed));
const slices: Slice[] = [];
const wanted = Math.ceil(Number(values.repos) / (BANDS.length * LANGUAGES.length));

// Every slice is searched first, so the seeded shuffle that picks repositories sees each pool whole.
const pools: { language: string; band: (typeof BANDS)[number]; repos: Repo[] }[] = [];
for (const band of BANDS) {
  for (const language of LANGUAGES) {
    const found = new Map<string, Repo>();
    for (const [from, to] of shuffled([...WINDOWS], next).slice(0, WINDOWS_PER_SLICE)) {
      const created = `${from}..${to}`;
      try {
        const repos = await search(language, band, created);
        for (const repo of repos) found.set(repo.fullName, repo);
        slices.push({ language, band: band.name, created, found: repos.length });
      } catch {
        slices.push({ language, band: band.name, created, found: -1 });
        skip("search failed");
      }
    }
    pools.push({ language, band, repos: shuffled([...found.values()], next).filter((repo) => repo.size <= MAX_REPO_SIZE) });
    console.log(`${band.name} ${language}: ${found.size} repositories found`);
  }
}

const manifest: ManifestEntry[] = [];
const seenRepo = new Set<string>();
for (const { language, band, repos } of pools) {
  let taken = 0;
  let cursor = 0;
  // Clones run a few at a time, in blocks, so that the seeded order of `repos` still decides which
  // repositories are reached: concurrency changes how fast the block finishes, never which repos are in it.
  while (taken < wanted && cursor < repos.length) {
    // Never more clones in flight than repositories still wanted, or a block whose every clone succeeds
    // would leave snapshots on disk that the manifest does not list.
    const size = Math.min(CLONES_AT_ONCE, wanted - taken);
    const block = repos.slice(cursor, cursor + size).filter((repo) => !seenRepo.has(repo.fullName));
    cursor += size;
    for (const repo of block) seenRepo.add(repo.fullName);
    // One seeded generator per repository, so a clone that fails cannot shift what every later repo samples.
    const seeds = block.map(() => random(Math.floor(next() * 2 ** 31)));
    for (const entries of await Promise.all(block.map((repo, i) => take(repo, band.name, seeds[i]!)))) {
      if (entries.length === 0) continue;
      manifest.push(...entries);
      taken++;
    }
  }
  console.log(`${band.name} ${language}: ${taken} repositories kept after trying ${cursor}`);
}

manifest.sort((a, b) => a.file.localeCompare(b.file));
writeFileSync(
  `${values.out}/manifest.json`,
  `${JSON.stringify({ seed: Number(values.seed), source: "GitHub search", pushedSince: PUSHED_SINCE, licences: LICENCES, slices, files: manifest }, null, 2)}\n`,
);

const share = (kind: Kind) => `${manifest.filter((entry) => entry.kind === kind).length} ${kind}`;
console.log(`${new Set(manifest.map((entry) => entry.repo)).size} repositories, ${manifest.length} files: ${(["source", "test", "jsx"] as Kind[]).map(share).join(", ")}`);
console.log("skipped:", skipped);
